"""Write docs/results.md from every eval/results/test-*/ folder. Reporting only: no scoring logic here."""
import glob, json, os, sys

SYSTEMS = ("baseline", "cited", "verified")
METRICS = [("decision_accuracy", "Decision accuracy (higher is better)"),
           ("unsupported_run_rate", "Runs with at least one unsupported claim, scorer count (lower is better)"),
           ("injection_leak_rate", "Injected text in the payload, scorer count (lower is better)"),
           ("completeness", "Evidence completeness on contest cases (higher is better)")]
MAIN = "test-DeepSeek-V4-Flash-0731"


def _r(x):
    x = round(x, 2)
    return 0.0 if x == 0 else x


def f(c):
    return f"{_r(c['mean']):.2f} [{_r(c['lo']):.2f}, {_r(c['hi']):.2f}]"


def fp(c):
    return f"{_r(c['mean']):+.2f} [{_r(c['lo']):+.2f}, {_r(c['hi']):+.2f}]"


def block(d, level):
    s = json.load(open(d + "/summary.json"))
    rows = [json.loads(l) for l in open(d + "/results.jsonl")]
    failed = {x: sum(1 for r in rows if r[x].get("failed")) for x in SYSTEMS}
    run = s["run"]
    out = [f"{'#' * level} {run['model']}", "",
           f"{run['cases']} cases x {run['repeats']} repeats = {len(rows)} runs per system. Commit {str(run['commit'])[:8]}. Single run.", "",
           "| Metric | Baseline | Cited | Verified | Paired difference (baseline - verified) |", "|---|---|---|---|---|"]
    for key, label in METRICS:
        m = s["metrics"][key]
        pd = fp(m["paired_baseline_minus_verified"]) if "paired_baseline_minus_verified" in m else "n/a"
        out.append(f"| {label} | {f(m['baseline'])} | {f(m['cited'])} | {f(m['verified'])} | {pd} |")
    out += ["", f"Runs with no usable draft: baseline {failed['baseline']}, cited {failed['cited']}, verified {failed['verified']} of {len(rows)}.",
            "Consistency (same decision on every repeat): " + ", ".join(f"{k} {v:.2f}" for k, v in s["consistency"].items() if v is not None) + ".",
            "Cost per run (USD): " + ", ".join(f"{k} {v:.4f}" for k, v in s["cost_per_run_usd"].items()) + "."]
    cp = d + "/flag-classification.json"
    if os.path.exists(cp):
        c = json.load(open(cp))
        out.append("Scorer flags, hand-classified: " + ", ".join(f"{k} {v}" for k, v in sorted(c["counts"].items())) + f". Classified by {c['classified_by']}")
        out += ["", "Notes:"] + [f"- {n}" for n in c.get("notes", [])] if c.get("notes") else []
    else:
        out.append("Scorer flags, hand-classified: not classified yet.")
    return out + [""], s


def build(results_dir="eval/results"):
    dirs = sorted(glob.glob(os.path.join(results_dir, "test-*")))
    dirs = [d for d in dirs if os.path.exists(d + "/summary.json") and os.path.exists(d + "/results.jsonl")]
    main = [d for d in dirs if os.path.basename(d) == MAIN]
    rest = [d for d in dirs if os.path.basename(d) != MAIN]
    out = ["# Results (generated by eval/tables.py, do not edit by hand)", "",
           "Synthetic data, written by the system's author. Single runs on a frozen test split. 95% case-level cluster bootstrap intervals in brackets. "
           "Read the limits at the bottom before the numbers.", "",
           "Paired difference is baseline minus verified, per case. On a higher-is-better row a negative value favors Verified; on a lower-is-better row a positive value does. "
           "Each run records the commit it ran at. Code changed between runs (see docs/DECISIONS.md), including the verifier's evidence gating, which does not change behaviour on these synthetic cases. "
           "Blocks in the panel are in alphabetical order, not ranked.", ""]
    limits = []
    if main:
        out += ["## Headline: the ablation", ""]
        lines, s = block(main[0], 3)
        out += lines
        limits = s["limits"]
    if rest:
        out += ["## Cross-model panel (separate from the headline; never merged with it)", ""]
        for d in rest:
            lines, s = block(d, 3)
            out += lines
            limits = limits or s["limits"]
    out += ["## Limits", ""] + [f"- {x}" for x in limits] + [""]
    return "\n".join(out)


if __name__ == "__main__":
    open("docs/results.md", "w").write(build(sys.argv[1] if len(sys.argv) > 1 else "eval/results"))
    print("wrote docs/results.md")
